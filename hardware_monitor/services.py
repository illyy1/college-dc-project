"""The business logic and decisions made with the data the APIs return. The
network itself is api_client.py's job; this module never touches it.

- report_fault(): reports a hardware fault to GitHub, unless this
  computer's issue for it is still open. It decides whether to
  ask Gemini for a triage, lets the triage set the call's final priority,
  and composes the issue's text and labels.
- apply_triage(): the rule for a triage: the call takes the more urgent of
  its own priority (the hardware rule) and Gemini's, so Gemini can raise
  urgency but never lower it, and keeps the cause and the estimate.
- triage_summary(): the calculations from the triages for the history
  report: the common causes, the minutes per technician, the open backlog."""

from collections import Counter
from dataclasses import dataclass
from datetime import datetime

from .api_client import IssueResult, Triage, create_issue, find_open_issues, triage_fault
from .config import COMPUTER_NAME, GITHUB_REPO


@dataclass
class FaultReport:
    """What report_fault did: the GitHub issue's result, Gemini's triage (or
    why there is none: triage_error is None when Gemini wasn't asked), and
    the priority the issue was labelled with (None without a triage)."""
    issue: IssueResult
    triage: Triage | None = None
    triage_error: str | None = None
    priority: int | None = None
    already_open: bool = False       # this computer's issue for the fault was still open: nothing posted
    lookup_error: str | None = None  # why the open issues couldn't be checked (posted anyway)


def report_fault(desk, github_token, gemini_api_key, alert_key, title, message, request=None):
    """Reports a fault as a GitHub issue, unless this computer's issue for
    the same fault is still open: then nothing is posted and Gemini is not
    asked. If the open issues can't be checked, the issue is posted anyway (a
    duplicate is better than a lost alert). With a Gemini key, the fault is
    triaged first: the triage is applied to the call (`request`, if there is
    one), and the issue gets a priority-N label and a Triage section. Without
    a key, or when Gemini fails, the issue goes out as before."""
    labels = ["hardware-alert", alert_key]
    full_title = issue_title(title)  # with the computer's name: never sent to Gemini
    search = find_open_issues(github_token, GITHUB_REPO, tuple(labels))
    still_open = next((issue for issue in search.issues if issue.title == full_title), None)
    if still_open is not None:
        return FaultReport(IssueResult(True, issue_number=still_open.number, url=still_open.url,
                                       attempts=search.attempts), already_open=True)
    lookup_error = search.error if search.attempts else None  # attempts 0: nothing was sent (no token)

    body = issue_body(alert_key, message, request, desk.technician_for(request) if request is not None else None)
    triage, triage_error, priority = None, None, None

    if gemini_api_key:
        result = triage_fault(gemini_api_key, title, message, alert_key)
        triage, triage_error = result.triage, result.error
    if triage is not None:
        if request is not None:
            apply_triage(desk, request.request_id, triage)
        priority = request.priority if request is not None else triage.priority
        labels.append(f"priority-{priority}")
        body += triage_section(triage, priority)

    issue = create_issue(github_token, GITHUB_REPO, full_title, body, labels=labels)
    return FaultReport(issue, triage, triage_error, priority, lookup_error=lookup_error)


def issue_title(title):
    """The GitHub issue's title for a fault on this computer. The duplicate
    check matches it exactly, so this is its one definition."""
    return f"\U0001f6a8 [{COMPUTER_NAME}] {title}"


def issue_body(alert_key, message, request=None, technician=None):
    """The GitHub issue's text for a fault, and its maintenance call if there is one."""
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    body = (f"### Hardware Alert Triggered\n- **Computer:** `{COMPUTER_NAME}`\n- **Time:** {timestamp}"
            f"\n- **Component:** `{alert_key}`\n- **Details:** {message}")
    if request is not None:
        body += (f"\n- **Maintenance Call:** `{request.request_id}`"
                 f"\n- **Assigned Technician:** {technician.name if technician else 'unassigned'}")
    return body


def triage_section(triage, priority):
    """The GitHub issue's section for Gemini's triage. `priority` is the
    call's final one, which may be more urgent than Gemini's."""
    steps = "\n".join(f"{n}. {step}" for n, step in enumerate(triage.steps, 1))
    return ("\n\n### Triage (AI-generated by Gemini; check before acting)"
            f"\n- **Priority:** {priority} (1 = most urgent)"
            f"\n- **Likely cause:** {triage.cause}"
            f"\n- **Estimated repair:** about {triage.repair_minutes} min"
            f"\n\n{steps}")


def apply_triage(desk, request_id, triage):
    """Applies Gemini's triage to a call through the desk (under its lock,
    then saved). Raises ValueError for an unknown call."""
    def change(call):
        call.priority = min(call.priority, triage.priority)  # lower is more urgent
        call.cause = triage.cause
        call.estimated_minutes = triage.repair_minutes

    return desk.update_request(request_id, change)


@dataclass
class TriageSummary:
    triaged_calls: int
    causes: list                 # (cause, calls), most common first, ties alphabetical
    minutes_by_technician: dict  # tech_id -> estimated minutes of all their triaged calls
    open_backlog_minutes: int    # estimated minutes of the triaged calls still open


def triage_summary(history):
    """Calculations from Gemini's triages (apply_triage): how often each
    likely cause came up, the estimated work per technician, and the
    estimated work still open. Calls without a triage are left out."""
    triaged = [call for call in history if call.cause is not None and call.estimated_minutes is not None]
    minutes = Counter()
    for call in triaged:
        if call.assigned_tech_id:
            minutes[call.assigned_tech_id] += call.estimated_minutes
    return TriageSummary(
        triaged_calls=len(triaged),
        causes=most_first(Counter(call.cause for call in triaged)),
        minutes_by_technician=dict(minutes),
        open_backlog_minutes=sum(call.estimated_minutes for call in triaged if call.status != "RESOLVED"),
    )


def most_first(counts):
    """{name: number} as (name, number) pairs, largest first; ties alphabetical."""
    return sorted(counts.items(), key=lambda item: (-item[1], item[0]))
